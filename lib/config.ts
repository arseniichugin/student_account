/**
 * Демо-режим для публичного стенда конкурса: аккаунты общие для всех посетителей,
 * поэтому действия, которые могут «сломать» показ другим (смена пароля), отключены.
 * Включается переменной окружения DEMO_MODE=1.
 */
export function isDemoMode(): boolean {
  return process.env.DEMO_MODE === "1";
}
