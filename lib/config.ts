/**
 * Настройки кабинета из переменных окружения сервера.
 * Значения читаются на сервере: в клиентские компоненты их передают пропсами
 * (в браузере process.env.* без NEXT_PUBLIC_ пусты — там всегда было бы значение по умолчанию).
 */

/**
 * Название вуза в интерфейсе: заголовок вкладки, логотип, профиль. Меняется вместе с файлами
 * data/university/ (см. «Как заменить вуз» в data/university/README.md). По умолчанию — «Хогвартс».
 */
export const UNIVERSITY_NAME = process.env.UNIVERSITY_NAME?.trim() || "Хогвартс";

/**
 * Демо-режим для публичного стенда конкурса: аккаунты общие для всех посетителей,
 * поэтому действия, которые могут «сломать» показ другим (смена пароля), отключены.
 * Включается переменной окружения DEMO_MODE=1.
 */
export function isDemoMode(): boolean {
  return process.env.DEMO_MODE === "1";
}
