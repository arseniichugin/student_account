import { z } from "zod";

/** Наибольшая длина «О себе» — в символах после приведения переводов строк к \n и обрезки пробелов по краям. */
export const ABOUT_MAX_LENGTH = 1000;

// Управляющие символы, кроме перевода строки и табуляции: в обычном тексте им не место
// (а нулевой байт PostgreSQL и вовсе не принимает).
const CONTROL_CHARS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/;

/**
 * «О себе» — обычный текст: HTML не разбирается и при показе выводится как текст (React экранирует),
 * переводы строк сохраняются. Пустая строка — «очистить» (в базе null).
 */
export const aboutSchema = z
  .string({ error: "Введите текст" })
  .transform((s) => s.replace(/\r\n?/g, "\n").trim())
  .pipe(
    z
      .string()
      .max(ABOUT_MAX_LENGTH, `Не больше ${ABOUT_MAX_LENGTH} символов`)
      .refine((s) => !CONTROL_CHARS.test(s), "Текст содержит недопустимые символы"),
  );
